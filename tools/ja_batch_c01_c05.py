def key_for(block_id: str, index: int) -> str:
    safe = block_id.replace(".", "_").replace("-", "_")
    return f"er_v06_{safe}_{index:02d}"


def main() -> int:
    data = json.loads(CONTENT.read_text(encoding="utf-8"))
    chapters = {ch["id"]: ch for ch in data["chapters"]}
    overlay = json.loads(OVERLAY.read_text(encoding="utf-8")) if OVERLAY.exists() else {}
    expected: dict[str, str] = {}
    for cid, values in TRANS.items():
        keys = [
            key_for(block["id"], index)
            for block in chapters[cid]["blocks"]
            for index, _ in enumerate(block.get("lines", []), 1)
        ]
        if len(keys) != len(values):
            raise SystemExit(f"{cid}: {len(keys)} keys but {len(values)} translations")
        for key, value in zip(keys, values):
            expected[key] = value
    overlay.update(expected)
    OVERLAY.write_text(json.dumps(overlay, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Updated {OVERLAY} (+{len(expected)} keys, total {len(overlay)})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
