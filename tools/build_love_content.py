#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Compile Content/love_romance_v01.json into C# arrays and localization pairs."""
from __future__ import annotations

import json
from pathlib import Path


def presentation_cs(block: dict) -> str:
    spec = block.get("presentation") or {}
    if not spec:
        return ""
    mode = str(spec.get("mode") or "immediate")
    first = spec.get("backup1") or {}
    second = spec.get("backup2") or {}

    def esc(value):
        return str(value or "").replace("\\", "\\\\").replace('"', '\\"')

    return (
        'new StoryPresentationSpec("%s", "%s", "%s", "%s", "%s")'
        % (esc(mode), esc(first.get("sprite")), esc(first.get("name")),
           esc(second.get("sprite")), esc(second.get("name")))
    )


def build(root):
    root = Path(root)
    scenes = []
    for name in ("love_romance_v01.json", "love_romance_v02.json", "love_romance_v03.json"):
        path = root / "Content" / name
        if path.exists():
            scenes.extend(json.loads(path.read_text(encoding="utf-8")).get("scenes", []))
    zh = {}
    en = {}
    ui_path = root / "Content" / "love_ui.json"
    if ui_path.exists():
        ui = json.loads(ui_path.read_text(encoding="utf-8"))
        for key, pair in ui.items():
            if len(pair) != 2 or not pair[0] or not pair[1]:
                raise ValueError("Incomplete love UI translation: " + key)
            zh[key], en[key] = pair

    code = [
        "// <auto-generated> tools/build_love_content.py </auto-generated>",
        "using System.Collections.Generic;",
        "namespace EleanorRomance {",
        "public static class LoveContent {",
        "public readonly struct Line { public readonly string Speaker, Key; public Line(string s,string k) { Speaker=s;Key=k; } }",
        "private static readonly Dictionary<string,Line[]> Blocks = new Dictionary<string,Line[]> {",
    ]

    revised_cursors = []
    for scene in scenes:
        for choice in scene.get("choices", []):
            cid = choice.get("id")
            if not cid:
                continue
            base = "er_love_choice_" + cid
            zh[base + "_label"] = choice.get("label_zh", "")
            en[base + "_label"] = choice.get("label_en", "")
            zh[base + "_desc"] = choice.get("description_zh", "")
            en[base + "_desc"] = choice.get("description_en", "")

        for block in scene.get("blocks", []):
            bid = block["id"]
            if block.get("cursor_revision"):
                revision = int(block["cursor_revision"])
                revised_cursors.append(f'case "{bid}": return "cursor.r{revision}.{bid}";')
            entries = []
            for index, line in enumerate(block.get("lines", []), 1):
                key = f"er_love_{bid}_{index:02d}"
                zh[key] = line.get("text", "")
                en[key] = line.get("en", "")
                speaker = line.get("speaker", "Narrator").replace("\\", "\\\\").replace('"', '\\"')
                entries.append(f'new Line("{speaker}","{key}")')
            code.append('{"' + bid + '",new[] {' + ",".join(entries) + "}},")

    code += [
        "};",
        "public static Line[] Get(string id) => Blocks.TryGetValue(id,out var block) ? block : null;",
        "public static string CursorKey(string id) { switch (id) {",
        *revised_cursors,
        'default: return "cursor." + id; } }',
        "private static readonly Dictionary<string,StoryPresentationSpec> Presentations = new Dictionary<string,StoryPresentationSpec> {",
    ]
    for scene in scenes:
        for block in scene.get("blocks", []):
            spec = presentation_cs(block)
            if spec:
                code.append('{"' + block["id"] + '",' + spec + "},")
    code += [
        "};",
        "public static StoryPresentationSpec GetPresentation(string id) => Presentations.TryGetValue(id,out var spec) ? spec : null;",
        "}}",
    ]
    (root / "src" / "LoveContent.g.cs").write_text("\n".join(code) + "\n", encoding="utf-8")
    return zh, en
