#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Collect optional `expr` fields from Content JSON into ExpressionContent.g.cs."""
from __future__ import annotations

import json
from pathlib import Path

ALLOWED = {
    "neutral", "angry", "sad", "shy", "soft", "serious",
    "tired", "determined", "tsun", "smile", "tease", "hurt", "flustered",
}


def _add_story(exprs, data):
    for chapter in data.get("chapters", []):
        for block in chapter.get("blocks", []):
            for index, line in enumerate(block.get("lines", []), 1):
                expr = line.get("expr")
                if expr:
                    key = "er_v06_" + block["id"].replace(".", "_").replace("-", "_") + f"_{index:02d}"
                    exprs[key] = expr


def _add_maid(exprs, data):
    for block in data.get("blocks", []):
        for index, line in enumerate(block.get("lines", []), 1):
            expr = line.get("expr")
            if expr:
                exprs[f"er_maid_{block['id']}_{index:02d}"] = expr


def _add_dual(exprs, data):
    for scene in data.get("scenes", []):
        for block in scene.get("blocks", []):
            for index, line in enumerate(block.get("lines", []), 1):
                expr = line.get("expr")
                if expr:
                    exprs[f"er_dual_{block['id']}_{index:02d}"] = expr


def build(root):
    root = Path(root)
    exprs = {}
    for name, fn in (("story_v06.json", _add_story), ("maid_v05.json", _add_maid), ("dual_romance_v04.json", _add_dual)):
        path = root / "Content" / name
        if path.exists():
            fn(exprs, json.loads(path.read_text(encoding="utf-8")))
    bad = sorted({v for v in exprs.values() if v not in ALLOWED})
    if bad:
        raise SystemExit("Unknown expression tags: " + ", ".join(bad))
    lines = [
        "// <auto-generated> tools/build_expressions.py </auto-generated>",
        "using System.Collections.Generic;",
        "namespace EleanorRomance {",
        "public static class ExpressionContent {",
        "public static readonly Dictionary<string,string> ByKey = new Dictionary<string,string> {",
    ]
    for key in sorted(exprs):
        lines.append(f'{{"{key}","{exprs[key]}"}},')
    lines += ["};", "}", "}", ""]
    (root / "src" / "ExpressionContent.g.cs").write_text("\n".join(lines), encoding="utf-8")
    print(f"ExpressionContent.g.cs: {len(exprs)} tags")
    return len(exprs)


if __name__ == "__main__":
    import sys
    build(Path(__file__).resolve().parents[1])
