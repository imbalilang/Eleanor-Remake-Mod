"""Compile additive v0.5 content through the same CSV pipeline as v0.6."""
import json
from pathlib import Path

def build(root):
    root=Path(root)
    data=json.loads((root/'Content/maid_v05.json').read_text(encoding='utf-8'))
    english={}
    for en_path in sorted((root/'Content').glob('maid_v05_en_part*.json')):
        part=json.loads(en_path.read_text(encoding='utf-8'))
        if set(part)&set(english): raise ValueError(f'Duplicate translations in {en_path}')
        english.update(part)
    for extra_name in ['interaction_v1.json','relationship_choices_v1.json']:
        extra_path=root/'Content'/extra_name
        if not extra_path.exists():continue
        extra=json.loads(extra_path.read_text(encoding='utf-8'))
        for block in extra['blocks']:
            if block['id'] in english:raise ValueError('Duplicate interaction block: '+block['id'])
            data['blocks'].append(block)
            english[block['id']]=[line['en'] for line in block['lines']]
    zh={}; en={}; code=['// <auto-generated> tools/build_maid_content.py </auto-generated>',
        'using System.Collections.Generic;', 'namespace EleanorRomance {',
        'public static class MaidContent {',
        'public readonly struct Line { public readonly string Speaker, Key; public Line(string s,string k) { Speaker=s;Key=k; } }',
        'private static readonly Dictionary<string,Line[]> Blocks = new Dictionary<string,Line[]> {']
    for block in data['blocks']:
        entries=[]
        translated=english.get(block['id'],[])
        if translated and len(translated)!=len(block['lines']): raise ValueError(f"Translation length mismatch: {block['id']}")
        for i,line in enumerate(block['lines']):
            key=f"er_maid_{block['id']}_{i+1:02}"
            zh[key]=line['text']
            if i<len(translated): en[key]=translated[i]
            entries.append(f'new Line("{line["speaker"]}","{key}")')
        code.append('{"'+block['id']+'",new[] {'+','.join(entries)+'}},')
    code += ['};','public static Line[] Get(string id) => Blocks.TryGetValue(id,out var block) ? block : null;','}}']
    (root/'src/MaidContent.g.cs').write_text('\n'.join(code)+'\n',encoding='utf-8')
    ui=json.loads((root/'Content/maid_ui.json').read_text(encoding='utf-8'))
    for extra_path in [root/'Content/business_ui.json',root/'Content/dividend_ui.json',root/'Content/scav_ui.json',root/'Content/project_discount_ui.json',root/'Content/interaction_ui.json',root/'Content/relationship_choice_ui.json']:
        if not extra_path.exists():continue
        extra=json.loads(extra_path.read_text(encoding='utf-8'))
        if set(ui)&set(extra):raise ValueError('Duplicate UI keys in '+str(extra_path))
        ui.update(extra)
    for key,pair in ui.items():
        if len(pair)!=2 or not all(pair): raise ValueError('Incomplete UI translation: '+key)
        zh[key],en[key]=pair
    return zh,en
