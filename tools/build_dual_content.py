#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Compile Content/dual_romance_v04.json into C# arrays and localization pairs.

The stable JSON path is the source of truth, now upgraded to design v0.5. This module is
called by build_content.py so the mod keeps a single CSV generation path.
"""
from __future__ import annotations

import json
from pathlib import Path


def build(root):
    root = Path(root)
    path = root / "Content" / "dual_romance_v04.json"
    data = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {"scenes": []}
    zh = {}
    en = {}
    ui_path = root / "Content" / "dual_ui.json"
    if ui_path.exists():
        ui = json.loads(ui_path.read_text(encoding="utf-8"))
        for key, pair in ui.items():
            if len(pair) != 2 or not pair[0] or not pair[1]:
                raise ValueError("Incomplete dual UI translation: " + key)
            zh[key], en[key] = pair
    code = [
        "// <auto-generated> tools/build_dual_content.py </auto-generated>",
        "using System.Collections.Generic;",
        "namespace EleanorRomance {",
        "public static class DualContent {",
        "public readonly struct Line { public readonly string Speaker, Key; public Line(string s,string k) { Speaker=s;Key=k; } }",
        "private static readonly Dictionary<string,Line[]> Blocks = new Dictionary<string,Line[]> {",
    ]

    for scene in data.get("scenes", []):
        for choice in scene.get("choices", []):
            cid = choice.get("id")
            if not cid:
                continue
            base = "er_dual_choice_" + cid
            zh[base + "_label"] = choice.get("label_zh", "")
            en[base + "_label"] = choice.get("label_en", "")
            zh[base + "_desc"] = choice.get("description_zh", "")
            en[base + "_desc"] = choice.get("description_en", "")

        for block in scene.get("blocks", []):
            bid = block["id"]
            entries = []
            for index, line in enumerate(block.get("lines", []), 1):
                key = f"er_dual_{bid}_{index:02d}"
                zh[key] = line.get("text", "")
                en[key] = line.get("en", "")
                speaker = line.get("speaker", "Narrator").replace("\\", "\\\\").replace('"', '\\"')
                entries.append(f'new Line("{speaker}","{key}")')
            code.append('{"' + bid + '",new[] {' + ",".join(entries) + "}},")

    code += [
        "};",
        "public static Line[] Get(string id) => Blocks.TryGetValue(id,out var block) ? block : null;",
        "}}",
    ]
    (root / "src" / "DualContent.g.cs").write_text("\n".join(code) + "\n", encoding="utf-8")
    return zh, en
