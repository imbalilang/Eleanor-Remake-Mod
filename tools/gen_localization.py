def extract_source_keys():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    keys = set()
    for path in glob.glob(os.path.join(root, "src", "*.cs")):
        with open(path, encoding="utf-8") as f:
            text = f.read()
        keys.update(re.findall(r'L\.Get\("([^"]+)"', text))
        for a, b in re.findall(r'L\.Get\([^"\n]*\?\s*"([^"]+)"\s*:\s*"([^"]+)"', text):
            keys.add(a)
            keys.add(b)
    return keys


