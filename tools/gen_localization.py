    if missing_en:
        print("Missing en keys:", missing_en)
    if extra_zh:
        print("Extra zh keys:", extra_zh)
    if extra_en:
        print("Extra en keys:", extra_en)

    if missing_zh or missing_en:
        sys.exit(1)

    out_dir = os.path.join(root, "Localization")
    os.makedirs(out_dir, exist_ok=True)

    for code, table in (("zh", zh), ("en", en)):
        path = os.path.join(out_dir, code + ".csv")
        with open(path, "w", encoding="utf-8", newline="") as f:
            writer = csv.writer(f, quoting=csv.QUOTE_ALL, lineterminator="\n")
            for key in sorted(table):
                writer.writerow([key, table[key]])
        print("Wrote", path, len(table), "entries")

    print("OK")


