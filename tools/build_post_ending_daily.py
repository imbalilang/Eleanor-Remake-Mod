#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Compile Content/post_ending_daily_v1.json into src/PostEndingDailyContent.g.cs and zh/en localization maps."""
from __future__ import annotations

import json
from pathlib import Path


def build(root):
    root = Path(root)
    path = root / "Content" / "post_ending_daily_v1.json"
    zh: dict[str, str] = {}
    en: dict[str, str] = {}

    scenes = json.loads(path.read_text(encoding="utf-8")).get("scenes", []) if path.exists() else []

    by_route: dict[str, list[str]] = {"love": [], "maid": [], "rev": []}
    code = [
        "// <auto-generated> tools/build_post_ending_daily.py </auto-generated>",
        "using System.Collections.Generic;",
        "namespace EleanorRomance {",
        "public static class PostEndingDailyContent {",
        "public readonly struct Line { public readonly string Speaker, Key; public Line(string s, string k) { Speaker = s; Key = k; } }",
        "private static readonly Dictionary<string, Line[]> Scenes = new Dictionary<string, Line[]> {",
    ]

    for sc in scenes:
        sid = sc["id"]
        rt = sc["route"]
        if rt in by_route:
            by_route[rt].append(sid)
        entries = []
        for idx, ln in enumerate(sc.get("lines", []), 1):
            key = f"er_postdaily_{sid}_{idx:02d}"
            zh[key] = ln.get("text", "")
            en[key] = ln.get("en", "")
            sp = ln.get("speaker", "Narrator").replace("\\", "\\\\").replace('"', '\\"')
            entries.append(f'new Line("{sp}","{key}")')
        code.append('{"' + sid + '", new[] {' + ",".join(entries) + "}},")

    code += [
        "};",
        "private static readonly Dictionary<string, string[]> RouteOrder = new Dictionary<string, string[]> {",
    ]
    for rt, ids in by_route.items():
        arr = ",".join('"' + x + '"' for x in ids)
        code.append(f'{{"{rt}", new[] {{ {arr} }}}},')
    code += [
        "};",
        "public static Line[] Get(string id) => Scenes.TryGetValue(id, out var lines) ? lines : null;",
        "public static string[] ForRoute(string route) => RouteOrder.TryGetValue(route, out var ids) ? ids : null;",
        "}}",
    ]
    (root / "src" / "PostEndingDailyContent.g.cs").write_text("\n".join(code) + "\n", encoding="utf-8")
    return zh, en
