#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Compile Content/revolution_v1.json into C# arrays and localization pairs.

Called by tools/build_content.py. The JSON is the source of truth for the
revolution route; UI/choice strings live in Content/revolution_ui.json.
"""
from __future__ import annotations

import json
from pathlib import Path

SPEAKERS = {"eleanor", "player", "news"}


def _const(block_id: str) -> str:
    return "B_" + block_id.replace(".", "_").replace("-", "_").upper()


def build(root):
    root = Path(root)
    data = json.loads((root / "Content" / "revolution_v1.json").read_text(encoding="utf-8"))
    ui = json.loads((root / "Content" / "revolution_ui.json").read_text(encoding="utf-8"))

    zh = {}
    en = {}
    code = [
        "// <auto-generated> tools/build_revolution_content.py </auto-generated>",
        "using System.Collections.Generic;",
        "namespace EleanorRomance {",
        "public static class RevolutionContent {",
        "public readonly struct Line { public readonly string Speaker, Key; public Line(string s,string k) { Speaker=s;Key=k; } }",
    ]
    seen = set()
    for block in data.get("blocks", []):
        bid = block["id"]
        if bid in seen:
            raise ValueError("Duplicate revolution block: " + bid)
        seen.add(bid)
        code.append(f'public const string {_const(bid)} = "{bid}";')
    code.append("private static readonly Dictionary<string,Line[]> Blocks = new Dictionary<string,Line[]> {")
    for block in data.get("blocks", []):
        bid = block["id"]
        entries = []
        for index, line in enumerate(block.get("lines", []), 1):
            speaker = line.get("speaker", "eleanor")
            if speaker not in SPEAKERS:
                raise ValueError(f"Unknown revolution speaker {speaker!r} in {bid}")
            text = line.get("text", "")
            translated = line.get("en", "")
            if not text or not translated:
                raise ValueError(f"Incomplete revolution translation: {bid} line {index}")
            key = f"er_rev_{bid}_{index:02d}"
            zh[key] = text
            en[key] = translated
            entries.append(f'new Line("{speaker}","{key}")')
        code.append('{"' + bid + '",new[] {' + ",".join(entries) + "}},")
    code += [
        "};",
        "public static Line[] Get(string id) => Blocks.TryGetValue(id,out var block) ? block : null;",
        "}}",
    ]
    (root / "src" / "RevolutionContent.g.cs").write_text("\n".join(code) + "\n", encoding="utf-8")

    for key, pair in ui.items():
        if len(pair) != 2 or not pair[0] or not pair[1]:
            raise ValueError("Incomplete revolution UI translation: " + key)
        zh[key], en[key] = pair

    return zh, en
