#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Compile Content/maid_v2.json into src/MaidV2Content.g.cs and localization pairs."""
from __future__ import annotations

import json
from pathlib import Path


def esc(value: str) -> str:
    return (str(value or "")
            .replace("\\", "\\\\")
            .replace('"', '\\"')
            .replace("\r", "")
            .replace("\n", "\\n"))


def key_for(block_id: str, index: int) -> str:
    return f"er_maid_v2_{block_id}_{index:02d}"


def build(root):
    root = Path(root)
    data = json.loads((root / "Content" / "maid_v2.json").read_text(encoding="utf-8"))
    zh = {}
    en = {}
    blocks = []
    scenes = []

    for scene in data["scenes"]:
        sid = scene["id"]
        title_key = f"er_maid_v2_{sid}_title"
        zh[title_key] = scene["title_zh"]
        en[title_key] = scene.get("title_en") or scene["title_zh"]
        for block_id, block in scene["blocks"].items():
            entries = []
            for i, line in enumerate(block["lines"], 1):
                key = key_for(block_id, i)
                zh[key] = line["text"]
                en[key] = line.get("en") or line["text"]
                entries.append((line["speaker"], key, line.get("expr") or ""))
            blocks.append((block_id, entries))

        segments = []
        for seg in scene["segments"]:
            if seg["type"] == "lines":
                segments.append(("lines", seg["block"], None, None))
            elif seg["type"] == "result":
                segments.append(("result", None, seg["text"], None))
            elif seg["type"] == "choice":
                cid = seg["id"]
                prompt_key = None
                host_block = None
                if seg.get("attach_to_previous"):
                    if not segments or segments[-1][0] != "lines":
                        raise ValueError(f"{sid}/{cid}: inline choices require a preceding dialogue block")
                    host_block = segments.pop()[1]
                    if not scene["blocks"][host_block]["lines"] or "prompt" in seg or "prompt_en" in seg:
                        raise ValueError(f"{sid}/{cid}: inline choices use the last line as their prompt")
                else:
                    prompt_key = f"er_maid_v2_{sid}_{cid.lower()}_prompt"
                    zh[prompt_key] = seg["prompt"]
                    en[prompt_key] = seg.get("prompt_en") or seg["prompt"]
                options = []
                for opt in seg["options"]:
                    label_key = f"er_maid_v2_{sid}_{cid.lower()}_{opt['id'].split('_')[-1]}"
                    zh[label_key] = opt["label"]
                    en[label_key] = opt.get("label_en") or opt["label"]
                    options.append((label_key, opt.get("block"), opt.get("result"),
                                    bool(opt.get("mainline"))))
                segments.append(("choice", prompt_key, int(seg["mainline"]), (cid, options, host_block)))
            else:
                raise ValueError(f"unknown segment type {seg['type']}")
        trades = []
        for trade in scene.get("trades", []):
            outcomes = list(trade.get("outcomes", {}).items())
            trades.append((trade["id"], trade["intent"], trade["type"],
                           trade.get("budget", ""), trade.get("client", ""), outcomes))
        scenes.append((sid, scene["code"], scene["act"], title_key, scene["client"],
                       scene["portrait"], scene["intent"], trades, segments))

    lines = [
        "// <auto-generated> tools/build_maid_v2_content.py </auto-generated>",
        "using System.Collections.Generic;",
        "namespace EleanorRomance {",
        "public static class MaidV2Content {",
        "public sealed class Line { public readonly string Speaker, Key, Expr; public Line(string s,string k,string e){Speaker=s;Key=k;Expr=e;} }",
        "public sealed class Block { public readonly string Id; public readonly Line[] Lines; public Block(string id,Line[] lines){Id=id;Lines=lines;} }",
        "public sealed class Option { public readonly string LabelKey, BlockId, Result; public readonly bool Mainline; public Option(string l,string b,string r,bool m){LabelKey=l;BlockId=b;Result=r;Mainline=m;} }",
        "public sealed class Choice { public readonly string Id, PromptKey; public readonly int Mainline; public readonly Option[] Options; public Choice(string id,string p,int m,Option[] o){Id=id;PromptKey=p;Mainline=m;Options=o;} }",
        "public sealed class Segment { public readonly string Type, BlockId, Result; public readonly Choice Choice; public Segment(string t,string b,string r,Choice c){Type=t;BlockId=b;Result=r;Choice=c;} }",
        "public sealed class Trade { public readonly string Id, Intent, Type, Budget, Client; public readonly Dictionary<string,string> Outcomes; public Trade(string id,string i,string t,string b,string c,Dictionary<string,string> o){Id=id;Intent=i;Type=t;Budget=b;Client=c;Outcomes=o;} }",
        "public sealed class Scene { public readonly string Id, TitleKey, Client, Portrait, Intent; public readonly int Code, Act; public readonly Trade[] Trades; public readonly Segment[] Segments; public Scene(string id,int code,int act,string title,string client,string portrait,string intent,Trade[] trades,Segment[] segs){Id=id;Code=code;Act=act;TitleKey=title;Client=client;Portrait=portrait;Intent=intent;Trades=trades;Segments=segs;} }",
        "private static readonly Dictionary<string,Block> BlockMap = new Dictionary<string,Block> {",
    ]
    for block_id, entries in blocks:
        line_entries = ",".join(
            f'new Line("{esc(speaker)}","{esc(key)}","{esc(expr)}")'
            for speaker, key, expr in entries)
        lines.append(f'{{"{esc(block_id)}",new Block("{esc(block_id)}",new[]{{{line_entries}}})}},')
    lines += [
        "};",
        "public static readonly Dictionary<string,Scene> SceneMap = new Dictionary<string,Scene> {",
    ]
    for sid, code, act, title_key, client, portrait, intent, trades, segments in scenes:
        trade_entries = []
        for tid, tint, ttype, tbudget, tclient, outcomes in trades:
            outcome_entries = ",".join(f'{{"{esc(k)}","{esc(v)}"}}' for k, v in outcomes)
            trade_entries.append(
                f'new Trade("{esc(tid)}","{esc(tint)}","{esc(ttype)}","{esc(tbudget)}","{esc(tclient)}",'
                f'new Dictionary<string,string>{{{outcome_entries}}})')
        seg_entries = []
        for seg in segments:
            if seg[0] == "lines":
                seg_entries.append(f'new Segment("lines","{esc(seg[1])}",null,null)')
            elif seg[0] == "result":
                seg_entries.append(f'new Segment("result",null,"{esc(seg[2])}",null)')
            else:
                _, prompt_key, mainline, (cid, options, host_block) = seg
                opt_entries = []
                for label_key, block_id, result, is_main in options:
                    opt_entries.append(
                        f'new Option("{esc(label_key)}",{("null" if not block_id else chr(34)+esc(block_id)+chr(34))},'
                        f'{("null" if not result else chr(34)+esc(result)+chr(34))},{"true" if is_main else "false"})')
                prompt_arg = f'"{esc(prompt_key)}"' if prompt_key else "null"
                block_arg = f'"{esc(host_block)}"' if host_block else "null"
                choice = (f'new Choice("{esc(cid)}",{prompt_arg},{mainline},'
                          f'new[]{{{",".join(opt_entries)}}})')
                seg_entries.append(f'new Segment("choice",{block_arg},null,{choice})')
        trade_array = f'new Trade[]{{{",".join(trade_entries)}}}'
        seg_array = f'new Segment[]{{{",".join(seg_entries)}}}'
        lines.append(
            f'{{"{esc(sid)}",new Scene("{esc(sid)}",{code},{act},"{esc(title_key)}",'
            f'"{esc(client)}","{esc(portrait)}","{esc(intent)}",'
            f'{trade_array},{seg_array})}},')
    lines += [
        "};",
        "public static Block GetBlock(string id){Block b;return BlockMap.TryGetValue(id,out b)?b:null;}",
        "public static Scene GetScene(string id){Scene s;return SceneMap.TryGetValue(id,out s)?s:null;}",
        "}",
        "}",
        "",
    ]
    (root / "src" / "MaidV2Content.g.cs").write_text("\n".join(lines), encoding="utf-8")
    print(f"MaidV2Content.g.cs: scenes={len(scenes)} blocks={len(blocks)}")
    return zh, en
