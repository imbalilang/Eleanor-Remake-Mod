#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Compile Content/story_v06.json into C# arrays and localization CSVs.

Run after parse_v06.py:
    python tools/parse_v06.py
    python tools/build_content.py
"""

from __future__ import annotations

import csv
import glob
import json
import os
import sys

SPEAKER_ENUM = {
    "narrator": "Narrator",
    "eleanor": "Eleanor",
    "player": "Player",
    "mother": "Mother",
    "lydia": "Lydia",
    "uncle": "Uncle",
    "thug": "Thug",
    "officer": "Officer",
    "news": "News",
    "security_notice": "SecurityNotice",
}


def key_for(block_id: str, index: int) -> str:
    safe = block_id.replace(".", "_").replace("-", "_")
    return f"er_v06_{safe}_{index:02d}"


def cs_const(block_id: str) -> str:
    return "B_" + block_id.replace(".", "_").replace("-", "_").upper()


def load_ui_text(root: str, code: str) -> dict:
    path = os.path.join(root, "tools", f"ui_text_{code}.json")
    if not os.path.exists(path):
        return {}
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def load_dialogue_en(root: str) -> dict:
    out = {}
    for path in sorted(glob.glob(os.path.join(root, "tools", "en_v06_part*.json"))):
        with open(path, encoding="utf-8") as f:
            part = json.load(f)
        for key, value in part.items():
            if key in out:
                print(f"Duplicate English key in {path}: {key}", file=sys.stderr)
            out[key] = value
    return out


def write_mod_csv(path: str, table: dict) -> None:
    """Write the format the game's ModLoader actually parses.

    ModLoader splits at the first comma and does NOT strip quotes from the
    key, but ParseCsvValue strips the surrounding quotes from the value.
    Therefore keys must be unquoted and values should be quoted with inner
    quotes doubled.
    """
    with open(path, "w", encoding="utf-8", newline="") as f:
        for key in sorted(table):
            if "," in key or "\n" in key or "\r" in key:
                raise ValueError(f"Illegal key for mod CSV: {key!r}")
            value = str(table[key])
            value = value.replace("\r", "").replace("\n", "\\n").replace('"', '""')
            f.write(f'{key},"{value}"\n')


def main() -> int:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    content_path = os.path.join(root, "Content", "story_v06.json")
    with open(content_path, encoding="utf-8") as f:
        data = json.load(f)

    chapters = data["chapters"]
    lines: list[str] = []
    lines.append("// <auto-generated> Generated by tools/build_content.py. Do not edit. </auto-generated>")
    lines.append("using System.Collections.Generic;")
    lines.append("")
    lines.append("namespace EleanorRomance")
    lines.append("{")
    lines.append("    public enum StorySpeaker")
    lines.append("    {")
    for enum_name in SPEAKER_ENUM.values():
        lines.append(f"        {enum_name},")
    lines.append("    }")
    lines.append("")
    lines.append("    public readonly struct StoryLine")
    lines.append("    {")
    lines.append("        public readonly StorySpeaker Speaker;")
    lines.append("        public readonly string Key;")
    lines.append("")
    lines.append("        public StoryLine(StorySpeaker speaker, string key)")
    lines.append("        {")
    lines.append("            Speaker = speaker;")
    lines.append("            Key = key;")
    lines.append("        }")
    lines.append("    }")
    lines.append("")
    lines.append("    public static class StoryV06Content")
    lines.append("    {")

    # Block id constants for compile-time references.
    for ch in chapters:
        for b in ch["blocks"]:
            lines.append(f"        public const string {cs_const(b['id'])} = \"{b['id']}\";")
    lines.append("")

    lines.append("        private static readonly Dictionary<string, StoryLine[]> Blocks =")
    lines.append("            new Dictionary<string, StoryLine[]>")
    lines.append("            {")
    zh = {}
    for ch in chapters:
        for b in ch["blocks"]:
            entries = []
            for i, ln in enumerate(b["lines"], 1):
                sp = SPEAKER_ENUM[ln["speaker"]]
                key = key_for(b["id"], i)
                zh[key] = ln["text"]
                entries.append(f"new StoryLine(StorySpeaker.{sp}, \"{key}\")")
            joined = ", ".join(entries)
            lines.append(f"                {{ \"{b['id']}\", new[] {{ {joined} }} }},")
    lines.append("            };")
    lines.append("")
    lines.append("        public static StoryLine[] Get(string id)")
    lines.append("        {")
    lines.append("            return Blocks.TryGetValue(id, out StoryLine[] block) ? block : null;")
    lines.append("        }")
    lines.append("    }")
    lines.append("}")

    out_cs = os.path.join(root, "src", "StoryV06Content.g.cs")
    with open(out_cs, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    # Merge system/UI text and generated dialogue text.
    ui_zh = load_ui_text(root, "zh")
    ui_en = load_ui_text(root, "en")
    dialogue_en = load_dialogue_en(root)
    all_zh = dict(ui_zh)
    all_zh.update(zh)
    all_en = dict(ui_en)
    all_en.update(dialogue_en)

    from build_maid_content import build as build_maid
    maid_zh, maid_en = build_maid(root)
    all_zh.update(maid_zh)
    all_en.update(maid_en)

    missing_en = sorted(set(all_zh) - set(all_en))
    os.makedirs(os.path.join(root, "Localization"), exist_ok=True)
    write_mod_csv(os.path.join(root, "Localization", "zh.csv"), all_zh)
    write_mod_csv(os.path.join(root, "Localization", "en.csv"), all_en)

    print(f"Wrote {out_cs}")
    print(f"Wrote Localization/zh.csv ({len(all_zh)} keys)")
    print(f"Wrote Localization/en.csv ({len(all_en)} keys)")
    if missing_en:
        print(f"English missing {len(missing_en)} dialogue keys (fallback in code).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
